# ---------------------------------------------------------------- helpers
def load(path):
    return cv2.imread(os.path.join(ROOT, path), cv2.IMREAD_COLOR)[:, :, ::-1].astype(np.float32)


def save_webp(path, rgba, quality=90):
    """quality above 100 writes lossless (lossy WebP halves the colour
    resolution, which softens red-on-white edges such as the gears')."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    bgra = np.clip(rgba, 0, 255).astype(np.uint8)[:, :, [2, 1, 0, 3]]
    ok = cv2.imwrite(path, bgra, [cv2.IMWRITE_WEBP_QUALITY, quality])
    assert ok, path


def fit_circle_soft(mask, feather):
    return np.clip(cv2.GaussianBlur(mask.astype(np.float32), (0, 0), feather), 0, 1)


def estimate_backdrop(I):
    lum = I.mean(2)
    sat = I.max(2) - I.min(2)
    flat = np.abs(cv2.Laplacian(lum, cv2.CV_32F, ksize=3)) < 10
    cand = (lum > 225) & (sat < 22) & flat
    k = 45
    w = cv2.GaussianBlur(cand.astype(np.float32), (0, 0), k)
    B = np.stack([cv2.GaussianBlur(I[:, :, c] * cand, (0, 0), k) for c in range(3)], 2)
    return np.clip(B / np.maximum(w, 1e-3)[..., None], 215, 255)


def rounded_rect_mask(shape, box, grow, side):
    """Mask of a card plus its shadow, grown on every side except the one the
    pipe leaves from, so the pipe's metal connector survives."""
    x0, y0, x1, y1 = box
    g = dict(left=grow, right=grow, top=grow, bottom=grow + 8)
    g[side] = 12  # the connector itself is protected separately
    m = np.zeros(shape, np.uint8)
    r = int(min(x1 - x0, y1 - y0) * 0.45)
    cv2.rectangle(m, (int(x0 - g["left"]), int(y0 - g["top"])), (int(x1 + g["right"]), int(y1 + g["bottom"])), 1, -1)
    return m.astype(bool)


def polar(img, c, r0, r1, nth, step=0.5):
    rs = np.arange(r0, r1, step)
    th = np.linspace(0, 2 * np.pi, nth, endpoint=False)
    X = (c[0] + rs[:, None] * np.cos(th)[None]).astype(np.float32)
    Y = (c[1] + rs[:, None] * np.sin(th)[None]).astype(np.float32)
    if img.ndim == 2:
        return cv2.remap(img, X, Y, cv2.INTER_LINEAR, borderMode=cv2.BORDER_REPLICATE), rs, th
    return np.stack([cv2.remap(img[..., i], X, Y, cv2.INTER_LINEAR, borderMode=cv2.BORDER_REPLICATE) for i in range(img.shape[2])], -1), rs, th


def unpolar(P, c, rs, th, shape, box):
    """Map a polar image back to cartesian pixels inside `box`."""
    x0, y0, x1, y1 = box
    yy, xx = np.mgrid[y0:y1, x0:x1].astype(np.float32)
    dx, dy = xx - c[0], yy - c[1]
    r = np.hypot(dx, dy)
    a = np.mod(np.arctan2(dy, dx), 2 * np.pi)
    ri = (r - rs[0]) / (rs[1] - rs[0])
    ai = a / (2 * np.pi) * len(th)
    inside = (ri >= 0) & (ri <= len(rs) - 1)
    # wrap angle by padding one column
    Pp = np.concatenate([P, P[:, :1]], 1)
    chans = [Pp] if Pp.ndim == 2 else [Pp[..., i] for i in range(Pp.shape[2])]
    out = [cv2.remap(ch.astype(np.float32), ai.astype(np.float32), np.clip(ri, 0, len(rs) - 1).astype(np.float32), cv2.INTER_LINEAR) for ch in chans]
    out = out[0] if len(out) == 1 else np.stack(out, -1)
    return out, inside


def fold_template(P, N):
    """Median tooth: fold the polar band by tooth pitch and take the median."""
    R, T = P.shape[:2]
    per = T // N
    Q = P[:, : per * N].reshape(R, N, per, *P.shape[2:])
    med = np.median(Q, axis=1)
    mad = np.median(np.abs(Q - med[:, None]), axis=1)
    tile = np.concatenate([med] * N, 1)
    madt = np.concatenate([mad] * N, 1)
    return tile, madt, per


def fill_along_theta(P, keep):
    """Replace P where keep is False by linear interpolation along each ring
    (circularly) from the kept samples at the same radius."""
    out = P.copy()
    T = P.shape[1]
    idx = np.arange(T)
    for i in range(P.shape[0]):
        k = keep[i]
        if k.sum() < 2:
            continue
        xs = np.nonzero(k)[0]
        xs_ext = np.concatenate([xs - T, xs, xs + T])
        for c in range(P.shape[2]):
            v = P[i, xs, c]
            out[i, :, c] = np.interp(idx, xs_ext, np.concatenate([v, v, v]))
    return out


def trace_tube(mask, start_xy):
    """Follow one tube from its connector end: take the tube's connected
    region, find its far end (the point furthest along the tube) and return
    the cheapest route there, which hugs the tube's centre-line. Works at
    any angle, unlike a scanline walk. Returns (x, y) points."""
    from scipy.sparse import coo_matrix
    from scipy.sparse.csgraph import dijkstra
    lab, n = ndi.label(mask, structure=np.ones((3, 3)))
    sx, sy = start_xy
    ys, xs = np.nonzero(lab)
    k = int(np.argmin((xs - sx) ** 2 + (ys - sy) ** 2))
    comp = lab == lab[ys[k], xs[k]]
    cy, cx = np.nonzero(comp)
    idx = -np.ones(mask.shape, np.int64)
    idx[cy, cx] = np.arange(len(cy))
    dt = ndi.distance_transform_edt(comp)
    rows, cols, w = [], [], []
    for dy, dx in ((0, 1), (1, 0), (1, 1), (1, -1)):
        ny, nx = cy + dy, cx + dx
        ok = (ny < mask.shape[0]) & (nx >= 0) & (nx < mask.shape[1])
        ok[ok] &= comp[ny[ok], nx[ok]]
        a, b = idx[cy[ok], cx[ok]], idx[ny[ok], nx[ok]]
        step = np.hypot(dy, dx)
        cost = step / (0.5 + dt[cy[ok], cx[ok]] + dt[ny[ok], nx[ok]])
        rows += [a, b]; cols += [b, a]; w += [cost, cost]
    G = coo_matrix((np.concatenate(w), (np.concatenate(rows), np.concatenate(cols))), shape=(len(cy),) * 2).tocsr()
    s0 = int(idx[ys[k], xs[k]])
    # far end: furthest by plain path length from the start
    hops, _ = dijkstra(G.copy().astype(bool).astype(float), indices=s0, return_predecessors=True)
    end = int(np.nanargmax(np.where(np.isfinite(hops), hops, -1)))
    _, pred = dijkstra(G, indices=s0, return_predecessors=True)
    path, j = [], end
    while j >= 0 and j != s0:
        path.append((cx[j], cy[j]))
        j = pred[j]
    path.append((cx[s0], cy[s0]))
    a = np.array(path[::-1], np.float32)
    if len(a) > 9:
        k7 = np.ones(7) / 7
        for d in (0, 1):
            a[3:-3, d] = np.convolve(a[:, d], k7, mode="valid")
    return a


def simplify(points, eps=0.6):
    a = np.array(points, np.float32).reshape(-1, 1, 2)
    s = cv2.approxPolyDP(a, eps, False).reshape(-1, 2)
    return s


def path_d(points):
    p = [(round(float(x), 1), round(float(y), 1)) for x, y in points]
    # Catmull-Rom through the points as cubic beziers: smooth and exact at knots
    d = f"M{p[0][0]} {p[0][1]}"
    for i in range(len(p) - 1):
        p0 = p[i - 1] if i > 0 else p[i]
        p1, p2 = p[i], p[i + 1]
        p3 = p[i + 2] if i + 2 < len(p) else p2
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        d += f"C{c1[0]:.1f} {c1[1]:.1f} {c2[0]:.1f} {c2[1]:.1f} {p2[0]} {p2[1]}"
    return d


def path_length(points):
    a = np.array(points, np.float32)
    return float(np.hypot(*np.diff(a, axis=0).T).sum())


