"""
Build the hero Growth Machine layers from Andrew's approved artwork.

Source of truth (never edited):  public/growth-machine-{desktop,mobile}-approved.webp
Everything in public/machine/ and components/growth-machine/manifest.json is
generated by this script. Re-run it after replacing either approved file:

    pip install -r tools/machine/requirements.txt
    python3 tools/machine/build_machine.py

What it makes, per artwork:

  body.webp     The machine with true alpha. The flattened cream backdrop is
                removed by colour-to-alpha against an estimate of that
                backdrop, so soft shadows and red glow survive as real
                translucency. The baked-in cards are erased (the page renders
                them as live text) and the AI-drawn nameplate lettering is
                cleaned off (the page lays the real vector logo over it).
  rig-*.webp    The motion rig, shown only while the gears turn. A base with
                every tooth band filled with what lies behind the teeth, one
                rotating ring per gear rebuilt from its own median tooth (so
                it is exactly periodic and can turn any number of teeth), and
                a static front layer for the glows and brackets that sit in
                front of the gears. At rest the page shows body.webp, so the
                resting machine is pixel-faithful to the approved art.
  warm.webp     A warm bloom of the central gear for the "engaged" state.

and the manifest: canvas size, crop, card boxes, gear centres and tooth
counts, the nameplate, and the centre-lines of every pipe and shaft (traced
from the artwork itself, so the light follows the real pipes).

All coordinates in this file are pixels of the approved artwork.
"""
