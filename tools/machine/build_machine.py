# ---------------------------------------------------------------- helpers
def load(path):
    return cv2.imread(os.path.join(ROOT, path), cv2.IMREAD_COLOR)[:, :, ::-1].astype(np.float32)


def save_webp(path, rgba, quality=90):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    bgra = np.clip(rgba, 0, 255).astype(np.uint8)[:, :, [2, 1, 0, 3]]
    ok = cv2.imwrite(path, bgra, [cv2.IMWRITE_WEBP_QUALITY, quality])
    assert ok, path


def fit_circle_soft(mask, feather):
    return np.clip(cv2.GaussianBlur(mask.astype(np.float32), (0, 0), feather), 0, 1)


def estimate_backdrop(I):
    lum = I.mean(2)
    sat = I.max(2) - I.min(2)
    flat = np.abs(cv2.Laplacian(lum, cv2.CV_32F, ksize=3)) < 10
    cand = (lum > 225) & (sat < 22) & flat
    k = 45
    w = cv2.GaussianBlur(cand.astype(np.float32), (0, 0), k)
    B = np.stack([cv2.GaussianBlur(I[:, :, c] * cand, (0, 0), k) for c in range(3)], 2)
    return np.clip(B / np.maximum(w, 1e-3)[..., None], 215, 255)


def rounded_rect_mask(shape, box, grow, side):
    """Mask of a card plus its shadow, grown on every side except the one the
    pipe leaves from, so the pipe's metal connector survives."""
    x0, y0, x1, y1 = box
    g = dict(left=grow, right=grow, top=grow, bottom=grow + 8)
    g[side] = 12  # the connector itself is protected separately
    m = np.zeros(shape, np.uint8)
    r = int(min(x1 - x0, y1 - y0) * 0.45)
    cv2.rectangle(m, (int(x0 - g["left"]), int(y0 - g["top"])), (int(x1 + g["right"]), int(y1 + g["bottom"])), 1, -1)
    return m.astype(bool)


def polar(img, c, r0, r1, nth, step=0.5):
    rs = np.arange(r0, r1, step)
    th = np.linspace(0, 2 * np.pi, nth, endpoint=False)
    X = (c[0] + rs[:, None] * np.cos(th)[None]).astype(np.float32)
    Y = (c[1] + rs[:, None] * np.sin(th)[None]).astype(np.float32)
    if img.ndim == 2:
        return cv2.remap(img, X, Y, cv2.INTER_LINEAR, borderMode=cv2.BORDER_REPLICATE), rs, th
    return np.stack([cv2.remap(img[..., i], X, Y, cv2.INTER_LINEAR, borderMode=cv2.BORDER_REPLICATE) for i in range(img.shape[2])], -1), rs, th


def unpolar(P, c, rs, th, shape, box):
    """Map a polar image back to cartesian pixels inside `box`."""
    x0, y0, x1, y1 = box
    yy, xx = np.mgrid[y0:y1, x0:x1].astype(np.float32)
    dx, dy = xx - c[0], yy - c[1]
    r = np.hypot(dx, dy)
    a = np.mod(np.arctan2(dy, dx), 2 * np.pi)
    ri = (r - rs[0]) / (rs[1] - rs[0])
    ai = a / (2 * np.pi) * len(th)
    inside = (ri >= 0) & (ri <= len(rs) - 1)
    # wrap angle by padding one column
    Pp = np.concatenate([P, P[:, :1]], 1)
    chans = [Pp] if Pp.ndim == 2 else [Pp[..., i] for i in range(Pp.shape[2])]
    out = [cv2.remap(ch.astype(np.float32), ai.astype(np.float32), np.clip(ri, 0, len(rs) - 1).astype(np.float32), cv2.INTER_LINEAR) for ch in chans]
    out = out[0] if len(out) == 1 else np.stack(out, -1)
    return out, inside


def fold_template(P, N):
    """Median tooth: fold the polar band by tooth pitch and take the median."""
    R, T = P.shape[:2]
    per = T // N
    Q = P[:, : per * N].reshape(R, N, per, *P.shape[2:])
    med = np.median(Q, axis=1)
    mad = np.median(np.abs(Q - med[:, None]), axis=1)
    tile = np.concatenate([med] * N, 1)
    madt = np.concatenate([mad] * N, 1)
    return tile, madt, per


def fill_along_theta(P, keep):
    """Replace P where keep is False by linear interpolation along each ring
    (circularly) from the kept samples at the same radius."""
    out = P.copy()
    T = P.shape[1]
    idx = np.arange(T)
    for i in range(P.shape[0]):
        k = keep[i]
        if k.sum() < 2:
            continue
        xs = np.nonzero(k)[0]
        xs_ext = np.concatenate([xs - T, xs, xs + T])
        for c in range(P.shape[2]):
            v = P[i, xs, c]
            out[i, :, c] = np.interp(idx, xs_ext, np.concatenate([v, v, v]))
    return out


def trace_pipe(red, axis, start, end, at, others_mask=None):
    """Walk along a pipe from its connector toward the flange, following the
    red run nearest the predicted position. Returns a list of (x, y)."""
    pts = []
    pos, vel = float(at), 0.0
    step = 1 if end > start else -1
    lab_cols = red if axis == "x" else red.T
    for s in range(start, end, step):
        col = lab_cols[:, s]
        lab, runs = ndi.label(col)
        if runs == 0:
            pos += vel
            continue
        cents = ndi.center_of_mass(col, lab, range(1, runs + 1))
        cents = np.array([c[0] for c in cents])
        pred = pos + vel
        j = np.argmin(np.abs(cents - pred))
        if abs(cents[j] - pred) > 9:
            pos = pred
            continue
        new = cents[j]
        vel = 0.7 * vel + 0.3 * (new - pos)
        pos = new
        pts.append((s, pos) if axis == "x" else (pos, s))
    # smooth
    a = np.array(pts, np.float32)
    if len(a) > 9:
        k = np.ones(7) / 7
        for d in (0, 1):
            a[3:-3, d] = np.convolve(a[:, d], k, mode="valid")
    return a


def simplify(points, eps=0.6):
    a = np.array(points, np.float32).reshape(-1, 1, 2)
    s = cv2.approxPolyDP(a, eps, False).reshape(-1, 2)
    return s


def path_d(points):
    p = [(round(float(x), 1), round(float(y), 1)) for x, y in points]
    # Catmull-Rom through the points as cubic beziers: smooth and exact at knots
    d = f"M{p[0][0]} {p[0][1]}"
    for i in range(len(p) - 1):
        p0 = p[i - 1] if i > 0 else p[i]
        p1, p2 = p[i], p[i + 1]
        p3 = p[i + 2] if i + 2 < len(p) else p2
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        d += f"C{c1[0]:.1f} {c1[1]:.1f} {c2[0]:.1f} {c2[1]:.1f} {p2[0]} {p2[1]}"
    return d


def path_length(points):
    a = np.array(points, np.float32)
    return float(np.hypot(*np.diff(a, axis=0).T).sum())


# ---------------------------------------------------------------- build
def build(kind, cfg):
    I = load(cfg["src"])
    H, W, _ = I.shape
    yy, xx = np.mgrid[:H, :W]
    B = estimate_backdrop(I)
    ink = np.clip((B - I) / B, 0, 1).max(2)
    R, G, Bc = I[..., 0], I[..., 1], I[..., 2]
    redness = np.clip((R - np.maximum(G, Bc) - 60) / 60, 0, 1)

    # ---- 1. alpha: solid machine, translucent shadow and glow, no backdrop
    hx, hy, hr = cfg["housing"]
    solid = (xx - hx) ** 2 + (yy - hy) ** 2 < hr ** 2
    strong = (ink > 0.16) & (yy < cfg["floor"] * H)
    strong = cv2.morphologyEx(strong.astype(np.uint8), cv2.MORPH_CLOSE, np.ones((3, 3), np.uint8)) > 0
    solid |= ndi.binary_fill_holes(strong)

    # erase the baked cards (and their shadows); the page draws them live
    card_mask = np.zeros((H, W), bool)
    side_in, side_out = cfg["cards_side"]
    for box in cfg["cards_in"]:
        card_mask |= rounded_rect_mask((H, W), box, 24, "right" if side_in == "left" else "bottom")
    for box in cfg["cards_out"]:
        card_mask |= rounded_rect_mask((H, W), box, 24, "left" if side_out == "right" else "top")
    # keep pipe connectors that poke into the grown mask: anything clearly
    # metal/red and outside the card itself
    inner = np.zeros((H, W), bool)
    for box in cfg["cards_in"] + cfg["cards_out"]:
        x0, y0, x1, y1 = box
        inner[y0 - 1:y1 + 2, x0 - 1:x1 + 2] = True
    # only near the edge the pipe leaves from
    near = np.zeros((H, W), bool)
    for box, side in [(b, side_in) for b in cfg["cards_in"]] + [(b, side_out) for b in cfg["cards_out"]]:
        x0, y0, x1, y1 = box
        if side == "left":
            near[y0:y1, x1 - 6:x1 + 30] = True
        elif side == "right":
            near[y0:y1, x0 - 30:x0 + 6] = True
        elif side == "top":
            near[y1 - 6:y1 + 30, x0:x1] = True
        else:
            near[y0 - 30:y0 + 6, x0:x1] = True
    connector = (ink > 0.22) & ~inner & near
    connector = cv2.dilate(connector.astype(np.uint8), np.ones((3, 3), np.uint8)) > 0
    card_mask &= ~connector
    # feathered, so the erase never leaves a seam in the surrounding shadow
    erase = np.clip(cv2.GaussianBlur(card_mask.astype(np.float32), (0, 0), 10) * 1.8, 0, 1)
    erase = np.where(connector, 0, np.maximum(erase, card_mask))

    soft_a = np.clip(ink * 1.2, 0, 1)
    soft_a[soft_a < 0.03] = 0
    # the studio floor below the machine: let its shadow thin out with depth
    floor_y = cfg["floor"] * H
    soft_a *= np.clip(1 - (yy - floor_y) / (0.08 * H), 0.25, 1)
    A = np.where(solid, 1.0, soft_a).astype(np.float32)
    A *= 1 - erase
    A = cv2.GaussianBlur(A, (0, 0), 0.7)
    A = np.clip(A, 0, 1)

    # ---- 2. clean the AI nameplate lettering
    pcx, pcy, pr = cfg["plate"]
    plate = (xx - pcx) ** 2 + (yy - pcy) ** 2 < (pr - 2) ** 2
    lum = I.mean(2)
    letters = plate & (lum < 205)
    letters = cv2.dilate(letters.astype(np.uint8), np.ones((5, 5), np.uint8)) > 0
    letters &= plate
    # fit a smooth surface (2D quartic per channel) to the bare plate
    bare = plate & ~letters
    ys, xs = np.nonzero(bare)
    def basis(x, y):
        u, v = (x - pcx) / pr, (y - pcy) / pr
        return np.stack([u ** i * v ** j for i in range(5) for j in range(5 - i)], -1)
    Mb = basis(xs.astype(np.float32), ys.astype(np.float32))
    clean = I.copy()
    ys2, xs2 = np.nonzero(plate)
    Mp = basis(xs2.astype(np.float32), ys2.astype(np.float32))
    for c in range(3):
        coef, *_ = np.linalg.lstsq(Mb, I[ys, xs, c], rcond=None)
        surf = Mp @ coef
        clean[ys2, xs2, c] = np.where(letters[ys2, xs2], surf, I[ys2, xs2, c])
    # a whisper of grain so the patch does not read as flat paint
    rng = np.random.default_rng(7)
    grain = rng.normal(0, 0.8, (H, W, 1)).astype(np.float32)
    clean = np.where(letters[..., None], clean + grain, clean)

    # unpremultiply against the backdrop so the cut-out reproduces the art on cream
    F = np.where(A[..., None] > 1e-3, (clean - (1 - A[..., None]) * B) / np.maximum(A[..., None], 1e-3), 0)
    F = np.where((A[..., None] > 0.97), clean, F)
    body = np.dstack([np.clip(F, 0, 255), A * 255])

    x0, y0, x1, y1 = cfg["crop"]
    out_dir = os.path.join(OUT_IMG, kind)
    save_webp(os.path.join(out_dir, "body.webp"), body[y0:y1, x0:x1], 92)

    # ---- 3. the gear rig
    gears = []
    base = clean.copy()
    layers = {}
    K = 72  # samples per tooth
    red_cfg = cfg["red"]
    all_gears = [dict(id="red", red=True, **red_cfg)] + [dict(red=False, **g) for g in cfg["greys"]]

    # tooth masks + templates, measured on the cleaned art
    prepared = []
    for g in all_gears:
        nth = g["N"] * K
        P, rs, th = polar(clean, g["c"], g["band"][0], g["band"][1], nth)
        Pred, _, _ = polar(redness, g["c"], g["band"][0], g["band"][1], nth)
        T, mad, per = fold_template(P, g["N"])
        if g["red"]:
            Tred, _, _ = fold_template(Pred[..., None], g["N"])
            alpha_t = np.clip(Tred[..., 0] * 1.6, 0, 1)
            # the inner solid band of the ring is always opaque
            alpha_t[rs < g["band"][0] + 10] = 1
            tooth = alpha_t > 0.5
        else:
            # In the median tooth the metal is bright and the gaps (whatever
            # lies behind them, averaged) are dark, so brightness separates them.
            lumT = T.mean(-1)
            contrast = np.percentile(lumT, 90, axis=1) - np.percentile(lumT, 10, axis=1)
            toothy = np.nonzero(contrast > 60)[0]
            tip = rs[toothy.max()] + 1.0
            alpha_t = np.clip((lumT - 80) / 40, 0, 1)
            # the solid hub band inside the tooth roots is always opaque
            alpha_t[rs < rs[toothy.min()]] = 1
            alpha_t *= np.clip((tip - rs) / 1.5, 0, 1)[:, None]
            tooth = alpha_t > 0.5
        prepared.append((g, P, rs, th, T, alpha_t, tooth))

    # base: fill each band's teeth with what is behind them (red first, it is on top)
    for g, P, rs, th, T, alpha_t, tooth in prepared:
        Pb, _, _ = polar(base, g["c"], rs[0], rs[-1] + 0.5, len(th))
        keep = ~cv2.dilate(tooth.astype(np.uint8), np.ones((3, 9), np.uint8)).astype(bool)
        if g["red"]:
            # Behind the red teeth is the dark interior of the machine. The
            # gaps also show bits of the function gears, which the grey rings
            # redraw themselves, so use the plain interior tone per radius.
            tone = np.stack([np.percentile(np.where(keep[..., None], Pb, np.nan)[i], 30, axis=0) if keep[i].any() else Pb[i].mean(0) for i in range(Pb.shape[0])])
            tone = np.nan_to_num(tone, nan=60.0)
            filled = np.where(keep[..., None], Pb, tone[:, None, :])
        else:
            filled = fill_along_theta(Pb, keep)
        r_out = g["band"][1] + 2
        box = (int(g["c"][0] - r_out), int(g["c"][1] - r_out), int(g["c"][0] + r_out) + 1, int(g["c"][1] + r_out) + 1)
        cart, inside = unpolar(filled, g["c"], rs, th, (H, W), box)
        bx0, by0, bx1, by1 = box
        sub = base[by0:by1, bx0:bx1]
        sub[inside] = cart[inside]
        base[by0:by1, bx0:bx1] = sub

    # rotating rings: the periodic template, alpha from the tooth mask
    for g, P, rs, th, T, alpha_t, tooth in prepared:
        r_out = int(np.ceil(g["band"][1])) + 2
        box = (int(round(g["c"][0])) - r_out, int(round(g["c"][1])) - r_out, int(round(g["c"][0])) + r_out, int(round(g["c"][1])) + r_out)
        rgb, inside = unpolar(T, g["c"], rs, th, (H, W), box)
        a, _ = unpolar(alpha_t, g["c"], rs, th, (H, W), box)
        a = np.where(inside, a, 0)
        layers[g["id"]] = (box, np.dstack([rgb, a * 255]))
        gears.append({"id": g["id"], "N": g["N"], "c": [round(g["c"][0] - x0, 2), round(g["c"][1] - y0, 2)],
                      "box": [box[0] - x0, box[1] - y0, box[2] - box[0], box[3] - box[1]],
                      "pivot": [round(g["c"][0] - box[0], 2), round(g["c"][1] - box[1], 2)]})

    # static front: things in front of the gears (shaft glows, brackets) that
    # differ strongly from the periodic gear, inside the tooth bands only
    front_a = np.zeros((H, W), np.float32)
    for g, P, rs, th, T, alpha_t, tooth in prepared:
        dev = np.abs(P - T).max(-1)
        Pred, _, _ = polar(redness, g["c"], rs[0], rs[-1] + 0.5, len(th))
        Plum = P.mean(-1)
        Tlum = T.mean(-1)
        if g["red"]:
            hot = (Plum - Tlum > 28)  # glow: much brighter than the plain tooth
        else:
            hot = (dev > 55) & (Pred < 0.3)  # brackets/bolts, not the red gear crossing
        hot = ndi.binary_opening(hot, np.ones((3, 3)))
        hot = ndi.binary_dilation(hot, np.ones((5, 7)))
        softm = cv2.GaussianBlur(hot.astype(np.float32), (0, 0), 1.5)
        r_out = g["band"][1] + 2
        box = (int(g["c"][0] - r_out), int(g["c"][1] - r_out), int(g["c"][0] + r_out) + 1, int(g["c"][1] + r_out) + 1)
        cart, inside = unpolar(softm, g["c"], rs, th, (H, W), box)
        bx0, by0, bx1, by1 = box
        front_a[by0:by1, bx0:bx1] = np.maximum(front_a[by0:by1, bx0:bx1], np.where(inside, cart, 0))
    # the outer radius of the red teeth band touches the shaft glows above/below:
    front = np.dstack([clean, np.clip(front_a, 0, 1) * 255])

    # rig crop: everything the gears can touch
    rx0 = int(min(gb["box"][0] for gb in gears)) + x0 - 2
    ry0 = int(min(gb["box"][1] for gb in gears)) + y0 - 2
    rx1 = int(max(gb["box"][0] + gb["box"][2] for gb in gears)) + x0 + 2
    ry1 = int(max(gb["box"][1] + gb["box"][3] for gb in gears)) + y0 + 2
    rig_box = [rx0 - x0, ry0 - y0, rx1 - rx0, ry1 - ry0]
    # the base only needs to cover the bands (body shows everywhere else)
    band_union = np.zeros((H, W), np.float32)
    for g in all_gears:
        d = np.hypot(xx - g["c"][0], yy - g["c"][1])
        band_union = np.maximum(band_union, ((d >= g["band"][0] - 3) & (d <= g["band"][1] + 3)).astype(np.float32))
    band_union = cv2.GaussianBlur(band_union, (0, 0), 1.0)
    rig_base = np.dstack([base, band_union * 255])
    save_webp(os.path.join(out_dir, "rig-base.webp"), rig_base[ry0:ry1, rx0:rx1], 90)
    save_webp(os.path.join(out_dir, "rig-front.webp"), front[ry0:ry1, rx0:rx1], 90)
    for gid, (box, rgba) in layers.items():
        save_webp(os.path.join(out_dir, f"gear-{gid}.webp"), rgba, 90)

    # ---- 4. warm bloom of the central gear (screen-blended on the page)
    rc = red_cfg["c"]
    d = np.hypot(xx - rc[0], yy - rc[1])
    ring = ((d > red_cfg["band"][0] - 6) & (d < red_cfg["band"][1] + 4)).astype(np.float32) * np.clip(redness * 1.5, 0, 1)
    bloom = cv2.GaussianBlur(ring, (0, 0), 6) * 0.8 + cv2.GaussianBlur(ring, (0, 0), 16) * 0.3
    bloom = np.clip(bloom, 0, 1)
    warm = np.dstack([np.full((H, W), 255.0), np.full((H, W), 78.0), np.full((H, W), 44.0), bloom * 255])
    pad = red_cfg["band"][1] + 60
    wb = (int(rc[0] - pad), int(rc[1] - pad), int(rc[0] + pad), int(rc[1] + pad))
    save_webp(os.path.join(out_dir, "warm.webp"), warm[wb[1]:wb[3], wb[0]:wb[2]], 85)

    # ---- 5. pipes: trace every pipe's centre-line from the artwork
    pipe_red = (redness > 0.25) & ~solid | ((redness > 0.25) & ~((xx - hx) ** 2 + (yy - hy) ** 2 < (hr - 40) ** 2))
    pipe_red = ndi.binary_opening(pipe_red, np.ones((2, 2)))
    def trace_set(spec, toward_machine):
        out = []
        for a in spec["at"]:
            pts = trace_pipe(pipe_red, cfg["axis"], spec["start"], spec["end"], a)
            if not toward_machine:
                pts = pts[::-1]
            pts = simplify(pts)
            out.append({"d": path_d([(x - x0, y - y0) for x, y in pts]), "len": round(path_length(pts), 1),
                        "from": [round(float(pts[0][0] - x0), 1), round(float(pts[0][1] - y0), 1)],
                        "to": [round(float(pts[-1][0] - x0), 1), round(float(pts[-1][1] - y0), 1)]})
        return out
    pipes_in = trace_set(cfg["pipes_in"], True)
    pipes_out = trace_set(cfg["pipes_out"], False)
    shaft = lambda pts: {"d": path_d([(x - x0, y - y0) for x, y in pts]), "len": round(path_length(pts), 1)}

    # nameplate: where the real logo goes (the AI lettering's own extent)
    ys_l, xs_l = np.nonzero(plate & (lum < 120) & ((xx - pcx) ** 2 + (yy - pcy) ** 2 < (0.92 * pr) ** 2))
    logo = {"cx": round((xs_l.min() + xs_l.max()) / 2 - x0, 1), "cy": round((ys_l.min() + ys_l.max()) / 2 - y0, 1),
            "w": int(xs_l.max() - xs_l.min())}

    def cards(boxes):
        return [[b[0] - x0, b[1] - y0, b[2] - b[0], b[3] - b[1]] for b in boxes]

    return {
        "size": [x1 - x0, y1 - y0],
        "crop": [x0, y0],
        "cardsIn": cards(cfg["cards_in"]),
        "cardsOut": cards(cfg["cards_out"]),
        "plate": {"cx": round(pcx - x0, 2), "cy": round(pcy - y0, 2), "r": pr},
        "logo": logo,
        "rig": rig_box,
        "warm": [wb[0] - x0, wb[1] - y0, wb[2] - wb[0], wb[3] - wb[1]],
        "gears": gears,
        "pipesIn": pipes_in,
        "pipesOut": pipes_out,
        "shaftIn": shaft(cfg["shaft_in"]),
        "shaftOut": shaft(cfg["shaft_out"]),
    }


