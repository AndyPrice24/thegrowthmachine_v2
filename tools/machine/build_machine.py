JOST = os.path.join(ROOT, "node_modules", "@fontsource", "jost", "files", "jost-latin-500-normal.woff2")


def glyph_advances(word):
    from fontTools.ttLib import TTFont
    f = TTFont(JOST)
    cmap, hm, upm = f.getBestCmap(), f["hmtx"], f["head"].unitsPerEm
    return [hm[cmap[ord(c)]][0] / upm for c in word]


def fit_circle_pts(pts):
    a = np.array(pts, np.float64)
    A = np.c_[2 * a[:, 0], 2 * a[:, 1], np.ones(len(a))]
    c, *_ = np.linalg.lstsq(A, (a ** 2).sum(1), rcond=None)
    return c[0], c[1], float(np.sqrt(c[2] + c[0] ** 2 + c[1] ** 2))


def arc_d(c, r, a0, a1):
    """SVG arc from angle a0 to a1 (degrees, screen space, clockwise positive)."""
    p0 = (c[0] + r * np.cos(np.radians(a0)), c[1] + r * np.sin(np.radians(a0)))
    p1 = (c[0] + r * np.cos(np.radians(a1)), c[1] + r * np.sin(np.radians(a1)))
    sweep = 1 if a1 > a0 else 0
    large = 1 if abs(a1 - a0) > 180 else 0
    return f"M{p0[0]:.1f} {p0[1]:.1f}A{r:.1f} {r:.1f} 0 {large} {sweep} {p1[0]:.1f} {p1[1]:.1f}"


def ang_of(c, p):
    return float(np.degrees(np.arctan2(p[1] - c[1], p[0] - c[0])))


def build_arcs(I, A, cfg, crop):
    """The process ring. The art's ring (dashed circles, red arcs, dots and
    the baked words) is cleared away completely, with soft edges so no strip
    is left behind. In its place the page draws one fine line joining the
    four stages, clockwise, each led by a small red step number. Words are
    Jost at the art's own measured size and spacing."""
    spec = cfg["arcs"]
    H, W, _ = I.shape
    yy, xx = np.mgrid[:H, :W]
    lum = I.mean(2)
    dots = spec["dots"]
    cx, cy, rc = fit_circle_pts([p for q in dots.values() for p in q])
    c = (cx, cy)
    d = np.hypot(xx - cx, yy - cy)
    ang = np.degrees(np.arctan2(yy - cy, xx - cx))

    # measure the art's own lettering to match size and spacing
    q, lo, hi = spec["measure"]
    m = (lum < 130) & (ang > lo) & (ang < hi) & (np.abs(d - rc) < 22)
    rs, angs = d[m], ang[m]
    r_lo, r_hi = np.percentile(rs, 1), np.percentile(rs, 99)
    cap = r_hi - r_lo
    r_mid = (r_lo + r_hi) / 2
    fs = cap / 0.7
    adv = glyph_advances("DIAGNOSE")
    span = np.radians(angs.max() - angs.min()) * r_mid
    track = (span - fs * (sum(adv) - 0.06 * (adv[0] + adv[-1]))) / (len(adv) - 1)
    # the portrait art is shown much smaller on a phone, so its ring text is
    # set larger than the art's own to stay readable
    k = spec.get("text_scale", 1.0)
    fs, cap, track = fs * k, cap * k, track * k

    # ---- clear the whole decorative ring, feathered at both edges
    r0, r1 = spec["erase"]
    ring = np.clip((d - r0) / 4, 0, 1) * np.clip((r1 + 6 - d) / 6, 0, 1)
    keep = np.zeros((H, W), np.float32)
    for bx0, by0, bx1, by1 in spec["protect"]:
        keep[by0:by1, bx0:bx1] = 1
    keep = cv2.GaussianBlur(keep, (0, 0), 2)
    erase = (ring * (1 - keep)).astype(np.float32)

    # ---- where the ring is free to run (not behind flanges or manifolds)
    A_after = A * (1 - erase)
    band = np.abs(d - r_mid) < cap / 2 + 9
    samples = np.arange(-180, 180, 0.25)
    blocked = np.zeros(len(samples), bool)
    angi = np.round((ang + 180) / 0.25).astype(int) % len(samples)
    in_block = np.zeros((H, W), bool)
    for bx0, by0, bx1, by1 in spec["block"]:
        in_block[by0:by1, bx0:bx1] = True
    solid_hits = np.bincount(angi[band & in_block & (A_after > 0.35)], minlength=len(samples))
    blocked = solid_hits > 0
    blocked = ndi.binary_dilation(blocked, np.ones(13), border_value=0)  # +-1.5 deg

    # ---- word groups: red step number, then the word, centred per quadrant
    def quad_centre(q):
        p_out, p_in = dots[q]
        a, b = ang_of(c, p_out), ang_of(c, p_in)
        return (a + b) / 2
    top_off = np.mean([abs(quad_centre(q) + 90) for q in ("TL", "TR")])
    bot_off = np.mean([abs(quad_centre(q) - 90) for q in ("BL", "BR")])
    centres = {"TL": -90 - top_off, "TR": -90 + top_off, "BL": 90 + bot_off, "BR": 90 - bot_off}

    fs_num = fs * 0.78
    gap = 0.55 * fs
    glyphs, nums, word_zones = [], [], []
    for quad, word in spec["words"].items():
        step = spec["steps"][quad]
        top = quad in ("TL", "TR")
        sgn = 1 if top else -1
        n_adv = [a * fs_num for a in glyph_advances(step)]
        w_adv = [a * fs for a in glyph_advances(word)]
        n_w = sum(n_adv) + 0.12 * fs_num * (len(step) - 1)
        w_w = sum(w_adv) + track * (len(word) - 1)
        total = n_w + gap + w_w
        mid = centres[quad]
        start = mid - sgn * np.degrees(total / 2 / r_mid)
        end = mid + sgn * np.degrees(total / 2 / r_mid)
        word_zones.append((min(start, end), max(start, end)))
        r_base = r_mid - cap / 2 if top else r_mid + cap / 2

        def place(chars, widths, spacing, offset, out, size):
            pos = offset
            for ch, w in zip(chars, widths):
                a = start + sgn * np.degrees((pos + w / 2) / r_mid)
                th = np.radians(a)
                out.append({"ch": ch, "x": round(cx + r_base * np.cos(th) - crop[0], 2),
                            "y": round(cy + r_base * np.sin(th) - crop[1], 2),
                            "rot": round(a + (90 if top else -90), 2), "size": round(size, 2)})
                pos += w + spacing
        place(step, n_adv, 0.12 * fs_num, 0.0, nums, fs_num)
        place(word, w_adv, track, n_w + gap, glyphs, fs)

    # ---- the chapter ring: hairlines and a minute track in the free arcs
    pad = np.degrees(0.9 * fs / r_mid)
    free = ~blocked.copy()
    for a0, a1 in word_zones:
        free &= ~((samples > a0 - pad) & (samples < a1 + pad))
    lab, n = ndi.label(free)
    # a run that wraps around +-180 is joined
    runs = []
    for i in range(1, n + 1):
        idx = np.nonzero(lab == i)[0]
        runs.append([samples[idx[0]], samples[idx[-1]]])
    if len(runs) > 1 and free[0] and free[-1]:
        first = runs.pop(0)
        runs[-1][1] = first[1] + 360
    # one fine line through the middle of the lettering joins the stages
    lines = []
    for a0, a1 in runs:
        if a1 - a0 < spec.get("min_track", 3):
            continue
        lines.append(arc_d(c, r_mid, a0, a1))

    shift = lambda dstr: _shift_path(dstr, crop)
    return erase, {
        "fontSize": round(fs, 2),
        "glyphs": glyphs,
        "nums": nums,
        "lines": [shift(l) for l in lines],
    }


def _shift_path(dstr, crop):
    import re
    nums = re.split(r"([MA])", dstr)
    out = []
    for i in range(1, len(nums), 2):
        cmd, args = nums[i], [float(v) for v in nums[i + 1].split()]
        if cmd == "M":
            out.append(f"M{args[0] - crop[0]:.1f} {args[1] - crop[1]:.1f}")
        else:
            r1, r2, rot, large, sweep, x, y = args
            out.append(f"A{r1:.1f} {r2:.1f} 0 {int(large)} {int(sweep)} {x - crop[0]:.1f} {y - crop[1]:.1f}")
    return "".join(out)


# ---------------------------------------------------------------- top globe
def fix_globe(I, cfg):
    """The art's bottom shaft ends in a neat red ring on a short stem; the
    top one ends in a misshapen red blob. Replace the blob with the bottom
    ring, mirrored about the line between the two shaft caps."""
    g = cfg.get("globe")
    if not g:
        return I
    I = I.copy()
    (x0, x1), (b0, b1), flip = g["x"], g["rows"], g["flip"]
    patch = I[b0:b1, x0:x1][::-1]
    t0 = flip - (b1 - 1)
    w = np.ones((b1 - b0, x1 - x0), np.float32)
    for k in range(4):  # feather the sides and the far end into the backdrop
        f = (k + 1) / 5
        w[:, k] = np.minimum(w[:, k], f)
        w[:, -1 - k] = np.minimum(w[:, -1 - k], f)
        w[k, :] = np.minimum(w[k, :], f)
    I[t0:t0 + (b1 - b0), x0:x1] = I[t0:t0 + (b1 - b0), x0:x1] * (1 - w[..., None]) + patch * w[..., None]
    return I


# ---------------------------------------------------------------- build
def build(kind, cfg):
    I = fix_globe(mirror_outlets(load(cfg["src"]), cfg), cfg)
    cfg = dict(cfg)
    cfg["cards_out"] = [mirror_box(b, cfg) for b in cfg["cards_in"]]
    if cfg["axis"] == "x":
        a = cfg["mirror"]["axis"]
        cfg["pipes_out"] = {"start": int(round(2 * a - cfg["pipes_in"]["start"])),
                            "end": int(round(2 * a - cfg["pipes_in"]["end"])), "at": cfg["pipes_in"]["at"]}
    else:
        a = cfg["mirror"]["axis"]
        cfg["pipes_out"] = {"start": int(round(2 * a - cfg["pipes_in"]["start"])),
                            "end": int(round(2 * a - cfg["pipes_in"]["end"])), "at": cfg["pipes_in"]["at"]}
    H, W, _ = I.shape
    yy, xx = np.mgrid[:H, :W]
    B = estimate_backdrop(I)
    ink = np.clip((B - I) / B, 0, 1).max(2)
    R, G, Bc = I[..., 0], I[..., 1], I[..., 2]
    redness = np.clip((R - np.maximum(G, Bc) - 60) / 60, 0, 1)

    # ---- 1. alpha: solid machine, translucent shadow and glow, no backdrop
    hx, hy, hr = cfg["housing"]
    solid = (xx - hx) ** 2 + (yy - hy) ** 2 < hr ** 2
    strong = (ink > 0.16) & (yy < cfg["floor"] * H)
    # below the machine only the shaft cap is solid; the rest is floor shadow
    strong &= (yy < cfg["floor_clear"]) | (np.abs(xx - cfg["housing"][0]) < 22)
    strong = cv2.morphologyEx(strong.astype(np.uint8), cv2.MORPH_CLOSE, np.ones((3, 3), np.uint8)) > 0
    solid |= ndi.binary_fill_holes(strong)

    # erase the baked cards (and their shadows); the page draws them live
    card_mask = np.zeros((H, W), bool)
    side_in, side_out = cfg["cards_side"]
    for box in cfg["cards_in"]:
        card_mask |= rounded_rect_mask((H, W), box, 24, "right" if side_in == "left" else "bottom")
    for box in cfg["cards_out"]:
        card_mask |= rounded_rect_mask((H, W), box, 24, "left" if side_out == "right" else "top")
    # keep pipe connectors that poke into the grown mask: anything clearly
    # metal/red and outside the card itself
    inner = np.zeros((H, W), bool)
    for box in cfg["cards_in"] + cfg["cards_out"]:
        x0, y0, x1, y1 = box
        inner[y0 - 1:y1 + 2, x0 - 1:x1 + 2] = True
    # only near the edge the pipe leaves from
    near = np.zeros((H, W), bool)
    for box, side in [(b, side_in) for b in cfg["cards_in"]] + [(b, side_out) for b in cfg["cards_out"]]:
        x0, y0, x1, y1 = box
        if side == "left":
            near[y0:y1, x1 - 6:x1 + 30] = True
        elif side == "right":
            near[y0:y1, x0 - 30:x0 + 6] = True
        elif side == "top":
            near[y1 - 6:y1 + 30, x0:x1] = True
        else:
            near[y0 - 30:y0 + 6, x0:x1] = True
    connector = (ink > 0.22) & ~inner & near
    connector = cv2.dilate(connector.astype(np.uint8), np.ones((3, 3), np.uint8)) > 0
    card_mask &= ~connector
    # feathered, so the erase never leaves a seam in the surrounding shadow
    erase = np.clip(cv2.GaussianBlur(card_mask.astype(np.float32), (0, 0), 10) * 1.8, 0, 1)
    erase = np.where(connector, 0, np.maximum(erase, card_mask))

    soft_a = np.clip(ink * 1.2, 0, 1)
    soft_a[soft_a < 0.03] = 0
    # the studio floor (reflection and cast shadow) goes: in 8-bit alpha it
    # banded. The page draws its own smooth contact shadow instead.
    fy = cfg["floor_clear"]
    soft_a *= np.clip((fy - yy) / 12, 0, 1)
    A = np.where(solid, 1.0, soft_a).astype(np.float32)
    A *= 1 - erase
    arc_erase, arcs = build_arcs(I, A, cfg, cfg["crop"])
    A *= 1 - arc_erase
    A = cv2.GaussianBlur(A, (0, 0), 0.7)
    A = np.clip(A, 0, 1)

    # ---- 2. clean the AI nameplate lettering
    pcx, pcy, pr = cfg["plate"]
    plate = (xx - pcx) ** 2 + (yy - pcy) ** 2 < (pr - 2) ** 2
    lum = I.mean(2)
    letters = plate & (lum < 205)
    letters = cv2.dilate(letters.astype(np.uint8), np.ones((5, 5), np.uint8)) > 0
    letters &= plate
    # fit a smooth surface (2D quartic per channel) to the bare plate
    bare = plate & ~letters
    ys, xs = np.nonzero(bare)
    def basis(x, y):
        u, v = (x - pcx) / pr, (y - pcy) / pr
        return np.stack([u ** i * v ** j for i in range(5) for j in range(5 - i)], -1)
    Mb = basis(xs.astype(np.float32), ys.astype(np.float32))
    clean = I.copy()
    ys2, xs2 = np.nonzero(plate)
    Mp = basis(xs2.astype(np.float32), ys2.astype(np.float32))
    for c in range(3):
        coef, *_ = np.linalg.lstsq(Mb, I[ys, xs, c], rcond=None)
        surf = Mp @ coef
        clean[ys2, xs2, c] = np.where(letters[ys2, xs2], surf, I[ys2, xs2, c])
    # a whisper of grain so the patch does not read as flat paint
    rng = np.random.default_rng(7)
    grain = rng.normal(0, 0.8, (H, W, 1)).astype(np.float32)
    clean = np.where(letters[..., None], clean + grain, clean)

    # unpremultiply against the backdrop so the cut-out reproduces the art on cream
    F = np.where(A[..., None] > 1e-3, (clean - (1 - A[..., None]) * B) / np.maximum(A[..., None], 1e-3), 0)
    F = np.where((A[..., None] > 0.97), clean, F)

    # haze: where the backdrop estimate missed, near-transparent specks
    # survive beside the machine and read as faint smudges on a light page.
    # Drop them where they are clear of the machine's solid parts; the red
    # glow round the pipes (strongly red) is kept.
    Fc = np.clip(F, 0, 255)
    redness = Fc[..., 0] - Fc[..., 1:].max(2)
    away = cv2.distanceTransform((A < 0.9).astype(np.uint8), cv2.DIST_L2, 5) > 6
    haze = (A < 0.1) & (redness < 70) & away
    haze = cv2.GaussianBlur(haze.astype(np.float32), (0, 0), 1.5)
    A = A * (1 - np.clip(haze * 1.6, 0, 1))

    # between the pipes: the art's soft reflections and cast shadows of the
    # pipes cross one another and read as smudges. Keep only the pipes, their
    # connectors and a tight soft edge.
    along_ = xx if cfg["axis"] == "x" else yy
    across_ = yy if cfg["axis"] == "x" else xx
    ps, pe = cfg["pipes_in"]["start"], cfg["pipes_in"]["end"]
    lo, hi = min(ps, pe) - 30, max(ps, pe) + 6
    ma = cfg["mirror"]["axis"]
    span = cfg["mirror"]["pipes"]
    zone = (((along_ > lo) & (along_ < hi)) | ((along_ > 2 * ma - hi) & (along_ < 2 * ma - lo))) \
        & (across_ > span[0]) & (across_ < span[1])
    tube = (R > 170) & (G < 140) & (Bc < 140) & (R - G > 70)
    # pipe or metal, judged by colour rather than alpha: where the backdrop
    # estimate failed (the mirrored outlets) pale backdrop came out opaque
    lum_i = I.mean(2)
    sat_i = I.max(2) - I.min(2)
    metal = (lum_i < 185) | (sat_i > 80)
    hard = (tube | metal) & (A > 0.25)
    # the same inside the decorative ring's band, where the flanges and
    # shafts are protected from the ring's erase and haze survived round them
    er0, er1 = cfg["arcs"]["erase"]
    dr = np.hypot(xx - hx, yy - hy)
    zone |= (dr > er0 - 4) & (dr < er1 + 4)
    hard = cv2.morphologyEx(hard.astype(np.uint8), cv2.MORPH_OPEN, np.ones((2, 2), np.uint8))
    hard = cv2.dilate(hard, np.ones((3, 3), np.uint8)).astype(np.float32)
    keep = np.clip(cv2.GaussianBlur(hard, (0, 0), 1.0) * 1.3, 0, 1)
    A = np.where(zone, A * keep, A)

    # last: small, faint fragments detached from the machine and the pipes
    frag = A > 0.02
    lab, n = ndi.label(frag, structure=np.ones((3, 3)))
    if n > 1:
        idx = np.arange(1, n + 1)
        size = ndi.sum(frag, lab, idx)
        peak = ndi.maximum(A, lab, idx)
        drop = idx[(size < 3000) & (peak < 0.3)]
        A = np.where(np.isin(lab, drop), 0, A)
    body = np.dstack([Fc, A * 255])

    x0, y0, x1, y1 = cfg["crop"]
    out_dir = os.path.join(OUT_IMG, kind)
    save_webp(os.path.join(out_dir, "body.webp"), body[y0:y1, x0:x1], 92)

    # ---- 3. the gear rig
    gears = []
    base = clean.copy()
    layers = {}
    K = 72  # samples per tooth
    red_cfg = cfg["red"]
    all_gears = [dict(id="red", red=True, **red_cfg)] + [dict(red=False, **g) for g in cfg["greys"]]

    # tooth masks + templates, measured on the cleaned art
    prepared = []
    for g in all_gears:
        nth = g["N"] * K
        P, rs, th = polar(clean, g["c"], g["band"][0], g["band"][1], nth)
        Pred, _, _ = polar(redness, g["c"], g["band"][0], g["band"][1], nth)
        T, mad, per = fold_template(P, g["N"])
        if g["red"]:
            Tred, _, _ = fold_template(Pred[..., None], g["N"])
            alpha_t = np.clip(Tred[..., 0] * 1.6, 0, 1)
            # the inner solid band of the ring is always opaque
            alpha_t[rs < g["band"][0] + 10] = 1
            tooth = alpha_t > 0.5
        else:
            # In the median tooth the metal is bright and the gaps (whatever
            # lies behind them, averaged) are dark, so brightness separates them.
            lumT = T.mean(-1)
            contrast = np.percentile(lumT, 90, axis=1) - np.percentile(lumT, 10, axis=1)
            toothy = np.nonzero(contrast > 60)[0]
            tip = rs[toothy.max()] + 1.0
            alpha_t = np.clip((lumT - 80) / 40, 0, 1)
            # the solid hub band inside the tooth roots is always opaque
            alpha_t[rs < rs[toothy.min()]] = 1
            alpha_t *= np.clip((tip - rs) / 1.5, 0, 1)[:, None]
            tooth = alpha_t > 0.5
        prepared.append((g, P, rs, th, T, alpha_t, tooth))

    # base: fill each band's teeth with what is behind them (red first, it is on top)
    for g, P, rs, th, T, alpha_t, tooth in prepared:
        Pb, _, _ = polar(base, g["c"], rs[0], rs[-1] + 0.5, len(th))
        keep = ~cv2.dilate(tooth.astype(np.uint8), np.ones((3, 9), np.uint8)).astype(bool)
        if g["red"]:
            # Behind the red teeth is the dark interior of the machine. The
            # gaps also show bits of the function gears, which the grey rings
            # redraw themselves, so use the plain interior tone per radius.
            # sample only gaps away from the function gears: those show the
            # warm, dark interior, not silver teeth
            thg = np.linspace(0, 2 * np.pi, Pb.shape[1], endpoint=False)
            px = g["c"][0] + rs[:, None] * np.cos(thg)[None]
            py = g["c"][1] + rs[:, None] * np.sin(thg)[None]
            clear = keep.copy()
            for o in all_gears:
                if not o["red"]:
                    clear &= np.hypot(px - o["c"][0], py - o["c"][1]) > o["band"][1] + 4
            masked = np.where(clear[..., None], Pb, np.nan)
            tone = np.stack([np.nanmedian(masked[i], axis=0) if clear[i].any() else Pb[i].mean(0) for i in range(Pb.shape[0])])
            tone = np.nan_to_num(tone, nan=50.0)
            filled = np.where(keep[..., None], Pb, tone[:, None, :])
        else:
            filled = fill_along_theta(Pb, keep)
        r_out = g["band"][1] + 2
        box = (int(g["c"][0] - r_out), int(g["c"][1] - r_out), int(g["c"][0] + r_out) + 1, int(g["c"][1] + r_out) + 1)
        cart, inside = unpolar(filled, g["c"], rs, th, (H, W), box)
        bx0, by0, bx1, by1 = box
        sub = base[by0:by1, bx0:bx1]
        sub[inside] = cart[inside]
        base[by0:by1, bx0:bx1] = sub

    # rotating rings: the periodic template, alpha from the tooth mask
    for g, P, rs, th, T, alpha_t, tooth in prepared:
        r_out = int(np.ceil(g["band"][1])) + 2
        box = (int(round(g["c"][0])) - r_out, int(round(g["c"][1])) - r_out, int(round(g["c"][0])) + r_out, int(round(g["c"][1])) + r_out)
        rgb, inside = unpolar(T, g["c"], rs, th, (H, W), box)
        a, _ = unpolar(alpha_t, g["c"], rs, th, (H, W), box)
        a = np.where(inside, a, 0)
        layers[g["id"]] = (box, np.dstack([rgb, a * 255]))
        gears.append({"id": g["id"], "N": g["N"], "c": [round(g["c"][0] - x0, 2), round(g["c"][1] - y0, 2)],
                      "box": [box[0] - x0, box[1] - y0, box[2] - box[0], box[3] - box[1]],
                      "pivot": [round(g["c"][0] - box[0], 2), round(g["c"][1] - box[1], 2)]})

    # static front: things in front of the gears (shaft glows, brackets) that
    # differ strongly from the periodic gear, inside the tooth bands only
    front_a = np.zeros((H, W), np.float32)
    for g, P, rs, th, T, alpha_t, tooth in prepared:
        dev = np.abs(P - T).max(-1)
        Pred, _, _ = polar(redness, g["c"], rs[0], rs[-1] + 0.5, len(th))
        Plum = P.mean(-1)
        Tlum = T.mean(-1)
        if g["red"]:
            hot = (Plum - Tlum > 28)  # glow: much brighter than the plain tooth
        else:
            hot = (dev > 55) & (Pred < 0.3)  # brackets/bolts, not the red gear crossing
        hot = ndi.binary_opening(hot, np.ones((3, 3)))
        hot = ndi.binary_dilation(hot, np.ones((5, 7)))
        softm = cv2.GaussianBlur(hot.astype(np.float32), (0, 0), 1.5)
        r_out = g["band"][1] + 2
        box = (int(g["c"][0] - r_out), int(g["c"][1] - r_out), int(g["c"][0] + r_out) + 1, int(g["c"][1] + r_out) + 1)
        cart, inside = unpolar(softm, g["c"], rs, th, (H, W), box)
        bx0, by0, bx1, by1 = box
        # Keep each gear's front layer out of the other gears: where the red
        # gear meshes with a function gear, the silver teeth seen between the
        # red teeth are brighter than the median red tooth and would otherwise
        # be frozen on top while the red ring turns under them.
        sub_y, sub_x = np.mgrid[by0:by1, bx0:bx1]
        others = [o for o in all_gears if o["id"] != g["id"] and (g["red"] or o["red"])]
        for o in others:
            near = np.hypot(sub_x - o["c"][0], sub_y - o["c"][1]) < o["band"][1] + 3
            cart = np.where(near, 0, cart)
        front_a[by0:by1, bx0:bx1] = np.maximum(front_a[by0:by1, bx0:bx1], np.where(inside, cart, 0))
    # the outer radius of the red teeth band touches the shaft glows above/below:
    front = np.dstack([clean, np.clip(front_a, 0, 1) * 255])

    # rig crop: everything the gears can touch
    rx0 = int(min(gb["box"][0] for gb in gears)) + x0 - 2
    ry0 = int(min(gb["box"][1] for gb in gears)) + y0 - 2
    rx1 = int(max(gb["box"][0] + gb["box"][2] for gb in gears)) + x0 + 2
    ry1 = int(max(gb["box"][1] + gb["box"][3] for gb in gears)) + y0 + 2
    rig_box = [rx0 - x0, ry0 - y0, rx1 - rx0, ry1 - ry0]
    # the base only needs to cover the bands (body shows everywhere else)
    band_union = np.zeros((H, W), np.float32)
    for g in all_gears:
        d = np.hypot(xx - g["c"][0], yy - g["c"][1])
        band_union = np.maximum(band_union, ((d >= g["band"][0] - 3) & (d <= g["band"][1] + 3)).astype(np.float32))
    band_union = cv2.GaussianBlur(band_union, (0, 0), 1.0)
    rig_base = np.dstack([base, band_union * 255])
    save_webp(os.path.join(out_dir, "rig-base.webp"), rig_base[ry0:ry1, rx0:rx1], 101)
    save_webp(os.path.join(out_dir, "rig-front.webp"), front[ry0:ry1, rx0:rx1], 101)
    for gid, (box, rgba) in layers.items():
        save_webp(os.path.join(out_dir, f"gear-{gid}.webp"), rgba, 101)

    # ---- 4. warm bloom of the central gear (screen-blended on the page)
    rc = red_cfg["c"]
    d = np.hypot(xx - rc[0], yy - rc[1])
    ring = ((d > red_cfg["band"][0] - 6) & (d < red_cfg["band"][1] + 4)).astype(np.float32) * np.clip(redness * 1.5, 0, 1)
    bloom = cv2.GaussianBlur(ring, (0, 0), 6) * 0.8 + cv2.GaussianBlur(ring, (0, 0), 16) * 0.3
    bloom = np.clip(bloom, 0, 1)
    warm = np.dstack([np.full((H, W), 255.0), np.full((H, W), 78.0), np.full((H, W), 44.0), bloom * 255])
    pad = red_cfg["band"][1] + 60
    wb = (int(rc[0] - pad), int(rc[1] - pad), int(rc[0] + pad), int(rc[1] + pad))
    save_webp(os.path.join(out_dir, "warm.webp"), warm[wb[1]:wb[3], wb[0]:wb[2]], 85)

    # ---- 5. pipes: trace every pipe's centre-line from the artwork
    # only the tubes' saturated red core: the pink glow and reflections round
    # them would pull the trace across onto a neighbouring pipe
    pipe_red = (R > 170) & (G < 120) & (Bc < 120) & (R - G > 90)
    pipe_red = cv2.morphologyEx(pipe_red.astype(np.uint8), cv2.MORPH_CLOSE, np.ones((5, 3) if cfg["axis"] == "x" else (3, 5), np.uint8)) > 0
    def trace_set(spec, toward_machine):
        out = []
        for a in spec["at"]:
            st = (spec["start"], a) if cfg["axis"] == "x" else (a, spec["start"])
            pts = trace_tube(pipe_red, st)
            if not toward_machine:
                pts = pts[::-1]
            pts = simplify(pts)
            out.append({"d": path_d([(x - x0, y - y0) for x, y in pts]), "len": round(path_length(pts), 1),
                        "from": [round(float(pts[0][0] - x0), 1), round(float(pts[0][1] - y0), 1)],
                        "to": [round(float(pts[-1][0] - x0), 1), round(float(pts[-1][1] - y0), 1)]})
        return out
    pipes_in = trace_set(cfg["pipes_in"], True)
    pipes_out = trace_set(cfg["pipes_out"], False)
    shaft = lambda pts: {"d": path_d([(x - x0, y - y0) for x, y in pts]), "len": round(path_length(pts), 1)}

    # nameplate: where the real logo goes (the AI lettering's own extent)
    ys_l, xs_l = np.nonzero(plate & (lum < 120) & ((xx - pcx) ** 2 + (yy - pcy) ** 2 < (0.92 * pr) ** 2))
    logo = {"cx": round((xs_l.min() + xs_l.max()) / 2 - x0, 1), "cy": round((ys_l.min() + ys_l.max()) / 2 - y0, 1),
            "w": int(xs_l.max() - xs_l.min())}

    gx, gy = cfg["card_grow"]
    def cards(boxes, side):
        # live cards grow away from the pipe side, for room to read
        out = []
        for b in boxes:
            bx0, by0, bx1, by1 = b
            if side == "left":
                bx0 -= gx
            elif side == "right":
                bx1 += gx
            out.append([bx0 - x0, by0 - y0, bx1 - bx0, by1 - by0])
        return out

    # draw order: function gears first, the red gear last (it sits in front of them)
    gears.sort(key=lambda gb: gb["id"] == "red")

    return {
        "size": [x1 - x0, y1 - y0],
        "crop": [x0, y0],
        "cardsIn": cards(cfg["cards_in"], cfg["cards_side"][0]),
        "cardsOut": cards(cfg["cards_out"], cfg["cards_side"][1]),
        "arcs": arcs,
        "plate": {"cx": round(pcx - x0, 2), "cy": round(pcy - y0, 2), "r": pr},
        "logo": logo,
        "rig": rig_box,
        "warm": [wb[0] - x0, wb[1] - y0, wb[2] - wb[0], wb[3] - wb[1]],
        "gears": gears,
        "pipesIn": pipes_in,
        "pipesOut": pipes_out,
        "shaftIn": shaft(cfg["shaft_in"]),
        "shaftOut": shaft(cfg["shaft_out"]),
    }


